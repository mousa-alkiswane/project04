/* =========================
   2. Language Switcher
========================= */

const languageButton = document.getElementById("languageButton");

let currentLanguage = "en";

function setLanguage(language) {
    if (!translations[language]) {
        return;
    }

    currentLanguage = language;

    // Update the document language and direction
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";

    // Update the page title
    document.title = translations[language].pageTitle;

    // Translate all elements with data-i18n
    const translatableElements = document.querySelectorAll("[data-i18n]");

    translatableElements.forEach(function (element) {
        const key = element.dataset.i18n;

        if (translations[language][key] !== undefined) {
            element.textContent = translations[language][key];
        }
    });

    // Translate placeholders
    const placeholderElements = document.querySelectorAll(
        "[data-i18n-placeholder]"
    );

    placeholderElements.forEach(function (element) {
        const key = element.dataset.i18nPlaceholder;

        if (translations[language][key] !== undefined) {
            element.placeholder = translations[language][key];
        }
    });

    // Translate image alt text
    const altElements = document.querySelectorAll("[data-i18n-alt]");

    altElements.forEach(function (element) {
        const key = element.dataset.i18nAlt;

        if (translations[language][key] !== undefined) {
            element.alt = translations[language][key];
        }
    });

    // Show the other available language on the button
    if (languageButton) {
        languageButton.textContent = language === "en" ? "العربية" : "English";
    }

    // Keep the theme button translated after changing languages
    updateThemeButton();

    // Update the current photo's alt text
    updatePhotoAlt();

    // Clear any old form message when changing language
    if (formMessage) {
        formMessage.textContent = "";
    }
}

if (languageButton) {
    languageButton.addEventListener("click", function () {
        const nextLanguage = currentLanguage === "en" ? "ar" : "en";
        setLanguage(nextLanguage);
    });
}


/* =========================
   3. Theme Switcher
========================= */

const themeButton = document.getElementById("themeButton");

function updateThemeButton() {
    if (!themeButton) {
        return;
    }

    const isDarkTheme = document.body.classList.contains("dark-theme");

    themeButton.textContent = isDarkTheme
        ? translations[currentLanguage].lightTheme
        : translations[currentLanguage].darkTheme;
}

if (themeButton) {
    themeButton.addEventListener("click", function () {
        document.body.classList.toggle("dark-theme");
        updateThemeButton();
    });
}


/* =========================
   4. Profile Photo Switcher
========================= */

const profilePhoto = document.getElementById("profilePhoto");
const changePhotoBtn = document.getElementById("changePhotoBtn");

const photos = [
    {
        src: "assets/profile.jpg",
        altKey: "profilePhotoAlt"
    },
    {
        src: "assets/professional.jpg",
        altKey: "professionalPhotoAlt"
    }
];

let currentPhoto = 0;
let isChangingPhoto = false;

function updatePhotoAlt() {
    if (!profilePhoto) {
        return;
    }

    const altKey = photos[currentPhoto].altKey;
    profilePhoto.alt = translations[currentLanguage][altKey];
}

if (profilePhoto && changePhotoBtn) {
    changePhotoBtn.addEventListener("click", function () {
        if (isChangingPhoto) {
            return;
        }

        isChangingPhoto = true;

        // Move to the next photo
        const nextPhoto = (currentPhoto + 1) % photos.length;

        // Start fade-out transition
        profilePhoto.style.opacity = "0";

        // Change the image after fade-out
        setTimeout(function () {
            currentPhoto = nextPhoto;
            profilePhoto.src = photos[currentPhoto].src;

            updatePhotoAlt();

            // Fade the new image in
            profilePhoto.style.opacity = "1";

            isChangingPhoto = false;
        }, 250);
    });
}


